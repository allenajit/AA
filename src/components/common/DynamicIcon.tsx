import React from 'react';
import {
  Code2,
  FileCode,
  Palette,
  Globe,
  Eye,
  Layers,
  Sparkles,
  Box,
  Paintbrush,
  Shapes,
  Zap,
  Server,
  Network,
  Database,
  Cpu,
  Radio,
  FastForward,
  CheckCircle2,
  ShieldCheck,
  ShieldAlert,
  GitBranch,
  Terminal,
  Github,
  Linkedin,
  ExternalLink,
  Award,
  GraduationCap,
  Trophy,
  Star,
  Medal,
  Calendar,
  Briefcase,
  Lightbulb,
  Activity,
  Mic,
  UserCheck,
  MessageSquareWarning,
  Gauge,
  AlertOctagon,
  Waves,
  Binary,
  Search,
  Mail,
  Sun,
  Moon,
  LucideIcon
} from 'lucide-react';

interface DynamicIconProps {
  name: string;
  className?: string;
  size?: number;
}

const iconRegistry: Record<string, LucideIcon> = {
  code2: Code2,
  filecode: FileCode,
  palette: Palette,
  globe: Globe,
  eye: Eye,
  layers: Layers,
  sparkles: Sparkles,
  box: Box,
  paintbrush: Paintbrush,
  shapes: Shapes,
  zap: Zap,
  server: Server,
  network: Network,
  database: Database,
  cpu: Cpu,
  radio: Radio,
  fastforward: FastForward,
  checkcircle2: CheckCircle2,
  shieldcheck: ShieldCheck,
  shieldalert: ShieldAlert,
  gitbranch: GitBranch,
  terminal: Terminal,
  github: Github,
  linkedin: Linkedin,
  externallink: ExternalLink,
  award: Award,
  graduationcap: GraduationCap,
  trophy: Trophy,
  star: Star,
  medal: Medal,
  calendar: Calendar,
  briefcase: Briefcase,
  lightbulb: Lightbulb,
  activity: Activity,
  mic: Mic,
  usercheck: UserCheck,
  messagesquarewarning: MessageSquareWarning,
  gauge: Gauge,
  alertoctagon: AlertOctagon,
  waves: Waves,
  binary: Binary,
  searchalert: Search,
  mail: Mail,
  sun: Sun,
  moon: Moon,
};

export const DynamicIcon: React.FC<DynamicIconProps> = ({ name, className = '', size = 20 }) => {
  const normalized = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  const IconComponent = iconRegistry[normalized] || Sparkles;

  return <IconComponent className={className} size={size} />;
};
